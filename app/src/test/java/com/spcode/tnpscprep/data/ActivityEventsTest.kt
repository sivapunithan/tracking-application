package com.spcode.tnpscprep.data

import com.spcode.tnpscprep.domain.ActivityType
import java.time.Instant
import java.time.ZoneId
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class ActivityEventsTest {
    private val t = Instant.parse("2026-11-17T20:00:00Z").toEpochMilli() // 01:30 on 18 Nov in India

    @Test fun the_local_date_is_decided_by_the_zone_at_write_time() {
        assertEquals("2026-11-18", ActivityEvents.build(ActivityType.NOTE, null, t, ZoneId.of("Asia/Kolkata")).localDate)
        assertEquals("2026-11-17", ActivityEvents.build(ActivityType.NOTE, null, t, ZoneId.of("UTC")).localDate)
    }

    @Test fun type_ref_and_timestamp_are_stored_as_given() {
        val e = ActivityEvents.build(ActivityType.TOPIC_PROGRESS, "pol.u1.t01", t, ZoneId.of("UTC"))
        assertEquals("TOPIC_PROGRESS", e.type); assertEquals("pol.u1.t01", e.refId); assertEquals(t, e.timestamp)
        assertEquals(0L, e.id) // autogenerated by the database
    }

    @Test fun details_are_a_small_json_object() {
        val e = ActivityEvents.build(ActivityType.FOCUS_SESSION, "sci", t) { put("minutes", 25) }
        assertEquals(25, Json.parseToJsonElement(e.details).jsonObject["minutes"]!!.jsonPrimitive.int)
    }

    @Test fun no_details_means_an_empty_object() = assertEquals("{}", ActivityEvents.build(ActivityType.NOTE, null, t).details)

    @Test fun a_missing_ref_is_null() = assertNull(ActivityEvents.build(ActivityType.HEALTH_LOG, null, t).refId)

    @Test fun type_names_are_stable() {
        assertEquals(
            listOf("FOCUS_SESSION", "TOPIC_PROGRESS", "NOTE", "AFFAIR_REVISED", "AFFAIR_ADDED", "MOCK_TEST", "HEALTH_LOG", "STEPS"),
            ActivityType.entries.map { it.name },
        )
    }
}
